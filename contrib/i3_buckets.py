# EWMH/XTEST abort files: a verified swayward_*_finding label wins over ABORT.
KEEP_REVIEWED = {"266-net-moveresize-window.t", "284-ewmh-visible-name.t",
                 "310-client-message-sticky.t", "286-root-window-mouse-binding.t"}
# Compositor-specific abort overrides (unreached rows only).
ABORT_ONE = {("sway", "113-urgent.t"): ("N-x11-all", "kill disconnects i3test X client"),
             ("sway", "264-dock-criteria.t"): ("N-x11-all", "kill disconnects i3test X client")}
EVIDENCE = {"kill": "kill disconnects i3test X client", "xtest": "XTEST blocks in xtest_sync_with_i3"}


def load(path):
    with open(ROOT / path, "rb") as f:
        return tomllib.load(f)


def display(compositor, name, commit):
    version = name.removeprefix(f"{compositor}-")
    return f"{compositor} `{version}`" if version == commit[:8] else f"{compositor} {version}"


class Snapshot:
    def __init__(self, compositor, name, unstable, pending):
        self.compositor, self.name = compositor, name
        self.files = load(f"i3/results/{name}.toml")["files"]
        self.rows = load(f"i3/classifications/{name}.toml")["classification"]
        self.labels = {(r["file"], r["assertion"]): r for r in self.rows}
        self.unstable = {(f, a) for c, f, a in unstable if c == compositor}
        self.stale = f"i3/results/{name}.toml" in pending
        self.outcome = {(f, a): o for f, e in self.files.items()
                        for o in ("pass", "skip", "fail", "unreached")
                        for a in e.get(f"{o}_assertions", [])}
        self.keys = [(f, a) for f in sorted(self.files) for a in range(1, self.files[f]["assertions"] + 1)]
        evidence = ROOT / f"i3/abort-causes/{name}.toml"
        self.evidence = {row["file"]: row["cause"]
                         for row in (load(evidence.relative_to(ROOT)).get("file", []) if evidence.exists() else [])}
        clash = set(self.evidence) & (set(ABORT) | {f for c, f in ABORT_ONE if c == compositor})
        if clash:
            raise SystemExit(f"{evidence}: files also have a source-decided abort override: {sorted(clash)}")
        self.bucket, self.cause = {}, {}
        # Snapshots whose results the partition reads; a pending one marks every figure.
        self.inputs = {self}

    def raw(self, key):
        if self.files[key[0]].get("flaky"):
            return "flaky"
        if key in self.unstable:
            return "unstable"
        return self.outcome[key]

    def classify(self, key, reference):
        f, a = key
        if self.files[f].get("flaky"):
            return "N-harness", "flaky file"
        if key in self.unstable:
            return "N-harness", "unstable assertion"
        o = self.outcome.get(key)
        if o is None:
            raise SystemExit(f"{self.name}: {f}:{a} has no outcome")
        if o == "pass":
            return "P", "pass"
        if o == "skip":
            return "S", "upstream skip"
        row = self.labels.get(key)
        if row is None:
            raise SystemExit(f"{self.name}: non-pass {f}:{a} has no classification")
        reason, verified = row["reason"], row["reason_verified"]
        if o == "unreached":
            if f in KEEP_REVIEWED and verified and reason.startswith("swayward_") \
                    and reason.endswith("_finding") and FAMILY.get(reason) == "N-gap":
                return "N-gap", "reviewed label kept in an EWMH/XTEST abort file: " + reason
            override = ABORT_ONE.get((self.compositor, f)) or ABORT.get(f)
            if override:
                return override[0], "abort point decided from the test source: " + override[1]
            if not verified:
                cause = self.evidence.get(f)
                if cause in EVIDENCE:
                    return "N-x11-all", "abort cause verified by a focused rerun: " + EVIDENCE[cause]
                return "N-harness", "unreached, abort cause undetermined"
        if reason in FAMILY:
            bucket = FAMILY[reason]
            if bucket == "KILL":
                if reference.bucket.get(key) == "P":
                    return "N-x11-sway", "kill label, sway passes"
                if o == "fail":
                    # The row ran, so the kill boundary cannot explain it: mirror sway.
                    return MIRROR, "kill label on a row that ran; mirrors sway"
                return "N-x11-all", "family: " + reason
            return bucket, ("declared deviation: " if reason in DECLARED else "family: ") + reason
        if reason in (NO_TAP, "unclassified"):
            return "N-gap", "fail, not yet reviewed"
        raise SystemExit(f"{self.name}: unmapped reason {reason!r} for {f}:{a}")

    def partition(self, reference):
        # Kill-labelled rows are bucketed by the reference's outcome, so every
        # figure of this snapshot can depend on the reference result.
        if any(r["reason"] == KILL for r in self.rows):
            self.inputs.add(reference)
        for key in self.keys:
            bucket, cause = self.classify(key, reference)
            if bucket == MIRROR:
                bucket = reference.bucket[key]
                bucket = "N-gap" if bucket in ("P", "S") else bucket
            self.bucket[key], self.cause[key] = bucket, cause
        for counts in (collections.Counter(self.bucket.values()),
                       collections.Counter(map(self.raw, self.keys))):
            if sum(counts.values()) != len(self.keys):
                raise SystemExit(f"{self.name}: partition does not sum to {len(self.keys)}")

    def view(self):
        return {k for k in self.keys if self.bucket[k] not in EXCLUDED}


def snapshots(pending=None):
    pins = load("pins.toml")
    if pending is None:
        pending = {row["path"] for row in load("pending.toml").get("pending", [])}
    unstable = {(u["compositor"], u["file"], a) for u in load("i3/unstable.toml").get("unstable", [])
                for a in u["assertions"]}
    snaps = {c: Snapshot(c, n, unstable, pending) for c, n in pins["snapshot"].items()}
    keys = {tuple(s.keys) for s in snaps.values()}
    if len(keys) != 1:
        raise SystemExit("i3 results do not cover the same assertions")
    reference = snaps[REFERENCE]
    reference.partition(reference)
    for snap in snaps.values():
        if snap is not reference:
            snap.partition(reference)
    return pins, snaps


def n(value):
    return f"{value:,}"


def dagger(*snaps):
    """† when any result these snapshots' partitions read is pending."""
    return "†" if any(s.stale for snap in snaps for s in snap.inputs) else ""


def render_region(compositor, pins, snaps):
    snap = snaps[compositor]
    mark = dagger(snap)
    review = "†" if snap.stale else ""
    counts = collections.Counter(snap.bucket.values())
    notes = collections.Counter(snap.cause.values())
    verified_aborts = sum(v for c, v in notes.items() if c.startswith("abort cause verified"))
    unreviewed = notes["fail, not yet reviewed"]
    cells = []
    for bucket in BUCKETS:
        cell = n(counts[bucket]) + mark
        if bucket == "N-x11-all" and verified_aborts:
            cell += f" ({n(verified_aborts)}{mark} abort causes verified by focused reruns)"
        if bucket == "N-gap" and unreviewed:
            cell += f" ({n(unreviewed)}{mark} not yet reviewed)"
        cells.append(cell)
    verified = sum(r.get("reason_verified") is True for r in snap.rows)
    unclassified = sum(r.get("reason") == "unclassified" for r in snap.rows)
    noun = "row" if len(snap.rows) == 1 else "rows"
    view = snap.view()
    vb = collections.Counter(snap.bucket[k] for k in view)
    vr = collections.Counter(snap.raw(k) for k in view)
    title = display(compositor, snap.name, pins[compositor])
    lines = [
        BEGIN,
        "| " + " | ".join(BUCKETS) + " |",
        "|" + " ---: |" * len(BUCKETS),
        "| " + " | ".join(cells) + " |",
        "",
        f"i3-suite review: {n(len(snap.rows))}{review} non-pass {noun}; {n(verified)}{review} verified, "
        f"{n(len(snap.rows) - verified)}{review} unverified, {n(unclassified)}{review} of them unclassified.",
        "",
        f"Comparable view of {title} ({n(len(view))}{mark} rows):",
        "",
        "| P | S | N-x11-sway | N-gap | " + " | ".join(RAW) + " |",
        "|" + " ---: |" * (4 + len(RAW)),
        "| " + " | ".join(n(x) + mark for x in [vb["P"], vb["S"], vb["N-x11-sway"], vb["N-gap"]]
                          + [vr[o] for o in RAW]) + " |",
        "",
    ]
    full = len(view) == len(snap.keys)
    others = [] if full else [c for c, s in snaps.items() if c != compositor and s.view() != set(s.keys)]
    if full:
        lines.append(f"Asymmetries: {compositor}'s view excludes no rows: every assertion is P or S.")
    for other in others:
        theirs = snaps[other]
        pair = dagger(snap, theirs)
        only = [k for k in view if k not in theirs.view()]
        shared = len(view) - len(only)
        passed = sum(snap.bucket[k] == "P" for k in only)
        lines.append(
            f"Asymmetries: {compositor}'s view and {other}'s view share {n(shared)}{pair} rows. "
            f"{n(len(only))}{pair} rows are in {compositor}'s view only, excluded by {other}'s labels, "
            f"and {compositor} passes {n(passed)}{pair} of them. By {other}'s bucket and cause:")
        lines.append("")
        by = collections.Counter((theirs.bucket[k], theirs.cause[k]) for k in only)
        for (bucket, cause), count in sorted(by.items(), key=lambda x: (-x[1], x[0])):
            cause = re.sub(r"(?<=: )([a-z0-9_]+)$", r"`\1`", cause)
            lines.append(f"- {n(count)}{pair} {bucket}: {cause}")
        lines.append("")
        lines.append(f"Measured on {compositor}'s view, {other} has "
                     f"{n(sum(theirs.bucket[k] == 'P' for k in view))}{pair} P.")
    lines.append(END)
    return "\n".join(lines)


def regions(text):
    return re.findall(rf"^{re.escape(BEGIN)}\n.*?^{re.escape(END)}$", text, re.S | re.M)


def write(path):
    pins, snaps = snapshots()
    text = Path(path).read_text()
    found = regions(text)
    if len(found) != len(snaps):
        raise SystemExit(f"{path}: needs {len(snaps)} generated i3-suite regions, found {len(found)}")
    # Regions appear in pins.toml [snapshot] order, one per block.
    for old, compositor in zip(found, snaps):
        text = text.replace(old, render_region(compositor, pins, snaps), 1)
    Path(path).write_text(text)


if __name__ == "__main__":
    if sys.argv[1:2] == ["--write"] and len(sys.argv) == 3:
        write(sys.argv[2])
    elif len(sys.argv) == 1:
        pins, snaps = snapshots()
        for compositor in snaps:
            print(render_region(compositor, pins, snaps), end="\n\n")
    else:
        raise SystemExit(__doc__)
