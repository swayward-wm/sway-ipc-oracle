#!/usr/bin/env python3
"""Bucket partition of the i3-suite results, and the README blocks built from it.

Usage: i3_buckets.py [--write README]   (print, or rewrite, the generated regions)

Every assertion of every pinned snapshot lands in exactly one bucket:
P pass; S upstream skip; N-i3 i3-only premise; N-x11-all X11 premise neither
measured stack meets (sway 1.12's wlroots XWM, swayward's xwayland-satellite);
N-x11-sway X11 metadata swayward cannot get through xwayland-satellite;
N-harness measurement artefact; N-gap comparable non-pass.

Precedence per assertion: flaky file > unstable assertion > pass > skip >
reviewed swayward_*_finding label in an EWMH/XTEST abort file > file-level
abort override (unreached rows only) > verified abort cause from
i3/abort-causes/ (unreached, unverified rows) > other unverified unreached
rows (N-harness) > family map > unverified fail (N-gap).

Inputs: pins.toml, pending.toml, i3/results, i3/classifications,
i3/unstable.toml, i3/abort-causes. contrib/tests/readme-snapshots requires each
README block's generated region to equal render_region().
"""
import collections
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUCKETS = ["P", "S", "N-i3", "N-x11-all", "N-x11-sway", "N-harness", "N-gap"]
EXCLUDED = {"N-i3", "N-x11-all", "N-harness"}
RAW = ["pass", "skip", "fail", "unreached", "unstable", "flaky"]
REFERENCE = "sway"
NO_TAP = "The pinned run emitted no TAP plan; retain this as an environment or harness finding."
KILL = "xwm_kill_client_fallback"
MIRROR = "MIRROR"
BEGIN = "<!-- i3-suite: generated by contrib/i3_buckets.py from the committed results; do not edit by hand -->"
END = "<!-- end i3-suite -->"

