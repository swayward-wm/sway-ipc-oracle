"""Render a minimised command list as a repro.sh and run it.
"""

import argparse
import os
from pathlib import Path
import shlex
import subprocess

from . import sequence
from .oracle import runner
from .signature import crash_key


REPRO_GRACE = 1.0  # after repro.sh exits, as after a replay's last step but for a whole script


def tally(results, key):
    """Counts of runs per outcome; crashed_key is a crash with key, crashed_other any other."""
    counts = {"runs": len(results), "crashed_key": 0, "crashed_other": 0, "survived": 0,
              "harness": 0}
    for result in results:
        if result["outcome"] == "crashed":
            counts["crashed_key" if crash_key(result) == key else "crashed_other"] += 1
        else:
            counts[result["outcome"]] += 1
    return counts


def reproduced(head_counts, base_counts):
    """Head crashed with the key in every run and base survived every run."""
    return (head_counts["crashed_key"] == head_counts["runs"] > 0
            and base_counts["survived"] == base_counts["runs"] > 0)


def run_script(binary, script, outputs, log_path, timeout):
    """Run a repro.sh once against a fresh sway started as replay starts it.

    The script gets the adapter's environment (sanitizer defaults, no
    WAYLAND_DISPLAY or DISPLAY), SWAYSOCK of that sway and the swaymsg next
    to the binary's build (<binary dir>/../swaymsg) first on PATH; its output
    goes to log_path with suffix .out. After it exits: REPRO_GRACE, then the
    same liveness check and signature as replay. Returns run_sequence's
    outcome fields plus signature; step is always None.
    """
    binary = Path(binary)

    def drive(adapter):
        env = {**adapter.env, "SWAYSOCK": str(adapter.socket),
               "PATH": f"{binary.parent.parent / 'swaymsg'}{os.pathsep}{os.environ.get('PATH', '')}"}
        for name in ("WAYLAND_DISPLAY", "DISPLAY"):
            env.pop(name, None)
        with open(log_path.with_suffix(".out"), "w") as output:
            subprocess.run(["sh", str(script)], env=env, stdout=output, stderr=subprocess.STDOUT,
                           timeout=timeout, check=False)

    outcome = sequence.run_on_sway(binary, sequence.layout_for(outputs), drive, log_path, timeout, REPRO_GRACE)
    return {**outcome, "signature": sequence.signature_of(outcome, log_path)}


def describe(provenance):
    """'<binary> (git <head8>, clean|dirty, ASan|no ASan)' for a repro.sh header."""
    git = provenance.get("git_head")
    state = {True: "dirty", False: "clean"}.get(provenance.get("dirty"), "-")
    asan = "ASan" if provenance.get("asan") else "no ASan"
    return f"{provenance.get('binary')} (git {git[:8] if git else 'unknown'}, {state}, {asan})"


def sway_config(outputs):
    """The config text replay's sway is started with for this output count."""
    # differential_adapter's sway setup without its factory, which tests replace.
    adapter = runner.SwayAdapter(argparse.Namespace(binary=Path("sway"), timeout=0, unpinned=True),
                                 Path("/tmp"), sequence.layout_for(outputs))
    adapter.config_text = runner.DIFFERENTIAL_CONFIGS["sway"]
    return adapter.rendered_config()


def render_repro(sent: list, outputs: int, header: dict):
    """A POSIX sh repro.sh for the sent commands of a replay, or None if one needs a fixture client.

    header: {"base", "head": binary provenance, "key": the signature key,
    "seed"}. The script starts nothing: it drives the sway named by SWAYSOCK
    with one swaymsg per step, and sleeps 1 s after each launched window so
    it maps. Its comment says how to start a sway set up as pr-check sets one
    up. xdg-hinted steps open a test client that is not a plain shell command.
    """
    if any(text.startswith("xdg-hinted ") for text in sent):
        return None
    layout = ("two headless 1280x720 outputs side by side" if outputs == 2
              else "one headless 1280x720 output")
    lines = [
        "#!/bin/sh",
        f"# Generated by pr-check from seed {header['seed']}: head crashes with",
        f"#   {header['key']}",
        "# and base survives.",
        f"#   base: {describe(header['base'])}",
        f"#   head: {describe(header['head'])}",
        "#",
        "# Run it against a fresh sway set up as pr-check sets one up:",
        f"# {layout}, no windows yet (the con_ids below are those of a",
        "# fresh sway), and swaymsg from the same build first on PATH. For example:",
        "#",
        "#   d=$(mktemp -d)",
        "#   cat >\"$d/config\" <<'EOF'",
        *(f"#   {line}" for line in sway_config(outputs).splitlines()),
        "#   EOF",
        "#   unset WAYLAND_DISPLAY DISPLAY",
        f"#   export XDG_RUNTIME_DIR=\"$d\" SWAYSOCK=\"$d/ipc.sock\" WLR_BACKENDS=headless WLR_HEADLESS_OUTPUTS={outputs}",
        "#   export ASAN_OPTIONS=detect_leaks=0 UBSAN_OPTIONS=halt_on_error=0:print_stacktrace=1",
        "#   path/to/build/sway/sway -c \"$d/config\" >\"$d/log\" 2>&1 & pid=$!",
        "#   while [ ! -S \"$SWAYSOCK\" ]; do sleep 0.1; done",
        "#   swaymsg 'output * mode --custom 1280x720@60Hz'",
        "#   sh repro.sh; sleep 1",
        "#   kill -0 $pid && echo survived || { echo crashed; grep -m1 SUMMARY \"$d/log\"; }",
        "",
    ]
    for text in sent:
        lines.append(f"swaymsg {shlex.quote(text)}")
        if text.startswith("exec foot"):
            lines.append("sleep 1")
    return "\n".join(lines) + "\n"
